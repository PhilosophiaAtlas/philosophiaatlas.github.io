import {test} from 'node:test';
import assert from 'node:assert/strict';
import {chromium,devices} from 'playwright';
import {spawn} from 'node:child_process';
import {setTimeout as delay} from 'node:timers/promises';

test('mobile preview: repeated taps, dismiss, navigate and return', {timeout:120000}, async()=>{
 const server=spawn(process.execPath,['node_modules/astro/astro.js','preview','--host','127.0.0.1','--port','4321'],{stdio:'ignore'});
 let browser;
 try{
  for(let i=0;i<60;i++){try{if((await fetch('http://127.0.0.1:4321/')).ok)break;}catch{}await delay(250);}
  browser=await chromium.launch({headless:true});
  const context=await browser.newContext({...devices['Pixel 7']});
  const page=await context.newPage();
  await page.goto('http://127.0.0.1:4321/');
  const link=page.locator('main a[href="/wiki/consciousness/"]').first();
  const dialog=page.locator('#wiki-preview');
  for(let i=0;i<3;i++){
   await link.tap();
   await dialog.waitFor({state:'visible'});
   await page.waitForFunction(()=>document.querySelector('#preview-title').textContent.trim()==='Ý thức'&&document.querySelector('#preview-summary').textContent.includes('nhóm hiện tượng'));
   assert.equal(new URL(page.url()).pathname,'/');
   await page.locator('#preview-dismiss').tap();
   await dialog.waitFor({state:'hidden'});
  }
  await link.tap();
  await dialog.waitFor({state:'visible'});
  // Simulate an accidental rapid activation of the explicit navigation control.
  await page.evaluate(()=>document.querySelector('#preview-open').dispatchEvent(new MouseEvent('click',{bubbles:true,detail:1})));
  assert.equal(new URL(page.url()).pathname,'/');
  await delay(500);
  await Promise.all([page.waitForURL('**/wiki/consciousness/'),page.locator('#preview-open').tap()]);
  await page.goBack();
  await link.tap();
  await dialog.waitFor({state:'visible'});
  assert.equal(new URL(page.url()).pathname,'/');
  await page.locator('#preview-dismiss').tap();
  await page.goto('http://127.0.0.1:4321/wiki/consciousness/');
  const section=page.locator('article .section-toggle').first();
  const panel=page.locator('#wiki-section-content-1');
  await section.tap();
  await panel.waitFor({state:'hidden'});
  assert.equal(await section.getAttribute('aria-expanded'),'false');
  await section.tap();await panel.waitFor({state:'visible'});
  await page.locator('#sections-toggle').tap();await panel.waitFor({state:'hidden'});
  await page.locator('#sections-toggle').tap();await panel.waitFor({state:'visible'});
  await page.locator('#reading-focus').tap();
  await page.locator('.site-header').waitFor({state:'hidden'});
  assert.equal(await page.locator('#reading-focus').getAttribute('aria-pressed'),'true');
  await page.reload();
  await page.locator('.site-header').waitFor({state:'hidden'});
  await page.locator('#reading-focus').tap();
  await page.locator('.site-header').waitFor({state:'visible'});
  await page.locator('#wiki-toc summary').tap();
  await page.locator('#wiki-toc a[href="#section-1"]').tap();
  assert.equal(new URL(page.url()).hash,'#section-1');
  await page.waitForFunction(()=>document.querySelector('#wiki-toc a[aria-current="location"]')!==null);
  await page.goto('http://127.0.0.1:4321/wiki/consciousness/');
  assert.match(await page.locator('.infobox').innerText(),/Consciousness/);
  await page.locator('.citation a').first().tap();
  await page.locator('#reference-preview').waitFor({state:'visible'});
  assert.match(await page.locator('#reference-content').innerText(),/Consciousness/);
  await page.locator('#reference-dismiss').tap();
  await page.locator('#reference-preview').waitFor({state:'hidden'});
  await page.locator('.citation a').first().tap();
  await page.locator('#reference-jump').tap();
  await page.waitForFunction(()=>location.hash==='#ref-1');
  await page.goto('http://127.0.0.1:4321/');
  const query=page.locator('#header-query');
  await query.fill('y thuc');
  await page.locator('#suggestion-list a[href="/wiki/consciousness/"]').waitFor({state:'visible'});
  await query.fill('consciousnes');
  await page.locator('#suggestion-list a[href="/wiki/consciousness/"]').waitFor({state:'visible'});
  await page.waitForFunction(()=>document.querySelector('#suggestion-list a')?.textContent.includes('Ý thức'));
  await query.press('ArrowDown');
  await Promise.all([page.waitForURL('**/wiki/consciousness/'),query.press('Enter')]);
  await page.goto('http://127.0.0.1:4321/wiki/y-thuc/');
  await page.waitForURL('**/wiki/consciousness/');
  assert.match(await page.locator('.hatnote').innerText(),/định hướng/);
  assert.match(await page.locator('.navbox').innerText(),/Triết học tâm trí/);
  await page.locator('.navbox summary').tap();assert.equal(await page.locator('.navbox').getAttribute('open'),null);
  await page.goto('http://127.0.0.1:4321/wiki/hard-problem/');
  await page.waitForURL('**/wiki/hard-problem-of-consciousness/');
  await page.goto('http://127.0.0.1:4321/wiki/consciousness-disambiguation/');
  assert.equal(await page.locator('.disambiguation-box li').count(),2);
  await page.goto('http://127.0.0.1:4321/category/');
  assert.match(await page.locator('.category-tree').innerText(),/Tâm trí và ý thức/);
  const parent=page.locator('.category-tree details').first();
  await parent.locator('summary').tap({position:{x:6,y:10}});
  assert.equal(await parent.getAttribute('open'),null);
  await page.goto('http://127.0.0.1:4321/wiki/consciousness/');
  const saved=page.locator('[data-library-action="saved"]'),watched=page.locator('[data-library-action="watched"]');
  await saved.tap();await watched.tap();
  assert.equal(await saved.getAttribute('aria-pressed'),'true');
  assert.equal(await watched.getAttribute('aria-pressed'),'true');
  await page.reload();await saved.waitFor({state:'visible'});assert.equal(await saved.getAttribute('aria-pressed'),'true');
  await page.goto('http://127.0.0.1:4321/library/');
  await page.locator('#library-list a[href="/wiki/consciousness/"]').waitFor();
  await page.locator('[data-tab="watched"]').tap();
  await page.waitForFunction(()=>document.querySelector('#library-list')?.textContent.includes('Chưa có thay đổi'));
  await page.evaluate(()=>{const k='philosophia-library-v1',s=JSON.parse(localStorage.getItem(k));s.watched[0].revision='0'.repeat(64);localStorage.setItem(k,JSON.stringify(s));window.dispatchEvent(new Event('philosophia-library-change'));});
  await page.getByText('Có thay đổi mới',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Đánh dấu đã đọc'}).tap();
  await page.getByText('Chưa có thay đổi',{exact:true}).waitFor();
  await page.locator('[data-tab="history"]').tap();
  await page.locator('#library-list a[href="/wiki/consciousness/"]').waitFor();
  await page.locator('#library-history-enabled').uncheck();
  await page.evaluate(()=>{const k='philosophia-library-v1',s=JSON.parse(localStorage.getItem(k));s.history=[];localStorage.setItem(k,JSON.stringify(s));});
  await page.goto('http://127.0.0.1:4321/wiki/consciousness/');
  await page.goto('http://127.0.0.1:4321/library/');
  await page.locator('[data-tab="history"]').tap();
  await page.getByText('Chưa có bài viết trong danh sách này.').waitFor();
  // Static reading remains available with JavaScript disabled.
  const noJS=await browser.newContext({javaScriptEnabled:false});
  const staticPage=await noJS.newPage();
  await staticPage.goto('http://127.0.0.1:4321/wiki/consciousness/');
  assert.match(await staticPage.locator('article').innerText(),/nhóm hiện tượng/);
  assert.equal(await staticPage.locator('article .section-toggle').count(),0);
  await noJS.close();
 }finally{await browser?.close();server.kill();}
});
